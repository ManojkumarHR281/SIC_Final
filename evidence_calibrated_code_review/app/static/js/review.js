document.addEventListener('DOMContentLoaded', () => {
  const qs = (selector, root = document) => root.querySelector(selector);
  const qsa = (selector, root = document) => Array.from(root.querySelectorAll(selector));
  const form = qs('#reviewForm');
  const fallback = qs('#codeInput');
  const fileInput = qs('#fileInput');
  const fileList = qs('#fileList');
  const uploadZone = qs('#uploadZone');
  const pendingFiles = new Map();
  let monacoEditor = null;
  let monacoApi = null;

  const value = () => monacoEditor ? monacoEditor.getValue() : (fallback?.value || '');
  const setValue = code => {
    if (monacoEditor) monacoEditor.setValue(code);
    if (fallback) fallback.value = code;
    refresh();
  };
  const languageId = () => qs('#language')?.value || 'python';
  const monacoLanguage = () => ({ c: 'cpp', cpp: 'cpp', csharp: 'csharp' }[languageId()] || languageId());

  const signalsFor = code => {
    const patterns = [
      { label: 'Possible unsafe evaluation', re: /\beval\s*\(/g, severity: 'High', category: 'Security' },
      { label: 'Shell command construction', re: /\bos\.system\s*\(|subprocess\.[a-z_]+\([^)]*shell\s*=\s*True|\bpopen\s*\(/g, severity: 'High', category: 'Security' },
      { label: 'Unsafe deserialization', re: /\bpickle\.loads?\s*\(|\bmarshal\.loads?\s*\(/g, severity: 'High', category: 'Security' },
      { label: 'Possible SQL concatenation', re: /(SELECT|INSERT|UPDATE|DELETE)[^"'\n]*["'][^"'\n]*\+/gi, severity: 'Medium', category: 'Security' },
      { label: 'Hardcoded credential literal', re: /(password|secret|api_key)\s*=\s*["'][^"']+["']/gi, severity: 'Medium', category: 'Security' },
      { label: 'Identity comparison with literal', re: /\bis\s+(?:\d+|["'][^"']+["'])/g, severity: 'Medium', category: 'Bug' },
      { label: 'Bare except block', re: /\bexcept\s*:/g, severity: 'Low', category: 'Bug' },
      { label: 'TODO marker', re: /\bTODO\b/g, severity: 'Low', category: 'Quality' },
    ];
    const found = [];
    patterns.forEach(pattern => {
      pattern.re.lastIndex = 0;
      let match;
      while ((match = pattern.re.exec(code)) !== null) {
        const line = code.slice(0, match.index).split('\n').length;
        found.push({ label: pattern.label, severity: pattern.severity, category: pattern.category, line });
      }
    });
    code.split('\n').forEach((row, index) => {
      if (row.length > 120) found.push({ label: 'Very long line', severity: 'Low', category: 'Quality', line: index + 1 });
    });
    return found.slice(0, 40);
  };

  const renderSignals = () => {
    const code = value();
    const signals = signalsFor(code);
    const lines = code ? code.split('\n').length : 0;
    const signalsNode = qs('#liveSignals');
    const problemsNode = qs('#problemList');
    const evidenceNode = qs('#evidencePreview');
    const logsNode = qs('#analysisLogs');
    const summaryNode = qs('#editorSummary');
    if (signalsNode) signalsNode.innerHTML = signals.length
      ? signals.slice(0, 6).map((signal, index) => `<button class="finding-jump" type="button" data-line="${signal.line}"><span class="badge-soft severity-${signal.severity}">${signal.severity}</span> ${signal.label}<small>${signal.category} · line ${signal.line}</small></button>`).join('')
      : '<div class="mini-row"><span class="label">No local signals detected.</span></div>';
    if (problemsNode) problemsNode.innerHTML = signals.length
      ? signals.map(signal => `<button class="finding-jump" type="button" data-line="${signal.line}"><span class="badge-soft severity-${signal.severity}">${signal.severity}</span> ${signal.label}<small>line ${signal.line} · ${signal.category}</small></button>`).join('')
      : '<div class="mini-row"><span class="label">No problems detected in the live preview.</span></div>';
    if (evidenceNode) evidenceNode.innerHTML = signals.length
      ? signals.slice(0, 10).map(signal => `<div class="mini-row"><span class="label">${signal.label}</span><span class="value">L${signal.line}</span></div>`).join('')
      : '<div class="mini-row"><span class="label">No evidence observations yet.</span></div>';
    if (logsNode) logsNode.innerHTML = `<div class="log-line"><span>scan</span> · ${lines} lines examined locally</div><div class="log-line"><span>signals</span> · ${signals.length} deterministic pattern observation(s)</div><div class="log-line"><span>mode</span> · ${qs('#mode')?.value || 'comprehensive'}</div>`;
    if (summaryNode) summaryNode.innerHTML = `<strong>${lines}</strong> lines · <strong>${new Blob([code]).size}</strong> bytes · <strong>${signals.length}</strong> live signal(s). Full evidence and calibrated confidence are generated by the analyzer after submission.`;
    qsa('[data-line]').forEach(button => button.addEventListener('click', () => revealLine(Number(button.dataset.line))));
    updateMarkers(signals);
  };

  const updateMarkers = signals => {
    if (!monacoApi || !monacoEditor) return;
    const model = monacoEditor.getModel();
    if (!model) return;
    const markers = signals.map(signal => ({
      severity: signal.severity === 'High' ? monacoApi.MarkerSeverity.Error : monacoApi.MarkerSeverity.Warning,
      message: `${signal.label} (${signal.category})`,
      startLineNumber: signal.line, startColumn: 1,
      endLineNumber: signal.line, endColumn: Math.max(2, model.getLineMaxColumn(signal.line)),
    }));
    monacoApi.editor.setModelMarkers(model, 'live-signals', markers);
  };

  const revealLine = line => {
    if (!line) return;
    if (monacoEditor) { monacoEditor.revealLineInCenter(line); monacoEditor.setPosition({ lineNumber: line, column: 1 }); monacoEditor.focus(); }
    else if (fallback) {
      const rows = fallback.value.split('\n');
      const start = rows.slice(0, line - 1).join('\n').length + (line > 1 ? 1 : 0);
      fallback.focus(); fallback.setSelectionRange(start, start + (rows[line - 1]?.length || 0));
    }
  };

  const refresh = () => {
    const code = value();
    const lines = code ? code.split('\n').length : 0;
    const count = qs('#lineCount');
    if (count) count.textContent = `${lines} lines · ${new Blob([code]).size} bytes`;
    if (qs('#fileLanguage')) qs('#fileLanguage').innerHTML = `<i class="bi bi-code-slash me-1"></i>${qs('#language')?.selectedOptions[0]?.text || 'Python'}`;
    renderSignals();
  };

  const renderFiles = () => {
    if (!fileList) return;
    qsa('#noFiles', fileList).forEach(node => node.remove());
    fileList.innerHTML = '';
    if (!pendingFiles.size) {
      fileList.innerHTML = '<div class="empty-chart" id="noFiles"><i class="bi bi-folder2-open"></i><strong>No files yet</strong><span>Paste code or upload sources.</span></div>';
      return;
    }
    pendingFiles.forEach((file, name) => {
      const chip = document.createElement('div');
      chip.className = 'file-chip';
      chip.innerHTML = `<i class="bi bi-file-code"></i><span>${name}</span><small class="text-muted">${(file.size / 1024).toFixed(1)} KB</small><button type="button" aria-label="Remove"><i class="bi bi-x"></i></button>`;
      chip.addEventListener('click', async event => {
        if (event.target.closest('button')) { pendingFiles.delete(name); renderFiles(); return; }
        setValue(await file.text());
        if (qs('#fileName')) qs('#fileName').textContent = name;
      });
      fileList.appendChild(chip);
    });
  };

  const addFiles = async files => {
    for (const file of Array.from(files || [])) {
      if (pendingFiles.size >= 8) { toast('Maximum of 8 files per review.', 'error'); break; }
      pendingFiles.set(file.name, file);
      if (!value().trim()) {
        setValue(await file.text());
        if (qs('#fileName')) qs('#fileName').textContent = file.name;
      }
    }
    renderFiles(); refresh();
  };

  let timer;
  const debouncedRefresh = () => { clearTimeout(timer); timer = setTimeout(refresh, 120); };
  fallback?.addEventListener('input', debouncedRefresh);
  qs('#language')?.addEventListener('change', () => {
    if (monacoApi && monacoEditor) monacoApi.editor.setModelLanguage(monacoEditor.getModel(), monacoLanguage());
    refresh();
  });
  qs('#mode')?.addEventListener('change', refresh);

  qs('#clearCode')?.addEventListener('click', () => { setValue(''); fallback?.focus(); });
  qs('#copyCode')?.addEventListener('click', async () => {
    try { await navigator.clipboard.writeText(value()); toast('Code copied.'); }
    catch (error) { toast('Clipboard unavailable.', 'error'); }
  });
  qs('#downloadCode')?.addEventListener('click', () => {
    const link = document.createElement('a');
    link.href = URL.createObjectURL(new Blob([value()], { type: 'text/plain' }));
    link.download = (qs('#fileName')?.textContent || 'source').trim() || 'source.txt';
    link.click(); URL.revokeObjectURL(link.href);
  });
  qs('#explainCode')?.addEventListener('click', async () => {
    openModal('AI explanation', '<p><span class="spinner"></span> Preparing explanation…</p>');
    try {
      const response = await fetch('/api/ai/explain', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'explain_code', code: value() }) });
      const result = await response.json();
      qs('#appModalBody').innerHTML = result.ok ? `<p>${result.text || result.message}</p>` : `<div class="warning-box">${result.error || result.reason}</div>`;
    } catch (error) { qs('#appModalBody').innerHTML = '<div class="warning-box">The AI endpoint is unavailable.</div>'; }
  });

  fileInput?.addEventListener('change', () => addFiles(fileInput.files));
  uploadZone?.addEventListener('click', () => fileInput?.click());
  uploadZone?.addEventListener('dragover', event => { event.preventDefault(); uploadZone.classList.add('dragover'); });
  uploadZone?.addEventListener('dragleave', () => uploadZone.classList.remove('dragover'));
  uploadZone?.addEventListener('drop', event => { event.preventDefault(); uploadZone.classList.remove('dragover'); addFiles(event.dataTransfer.files); });
  if (new URLSearchParams(location.search).has('upload')) setTimeout(() => fileInput?.click(), 80);

  qsa('[data-sample]').forEach(button => button.addEventListener('click', () => {
    setValue(button.dataset.sample);
    if (qs('#fileName')) qs('#fileName').textContent = 'sample.' + ({ python: 'py', javascript: 'js', typescript: 'ts', java: 'java', cpp: 'cpp', c: 'c', csharp: 'cs', php: 'php', go: 'go', ruby: 'rb' }[languageId()] || 'txt');
    toast('Sample loaded into the editor.');
  }));

  qsa('[data-collapse-panel]').forEach(button => button.addEventListener('click', () => {
    const panel = document.getElementById(button.dataset.collapsePanel);
    const body = panel?.querySelector('[data-panel-body]');
    if (body) body.hidden = !body.hidden;
    panel?.classList.toggle('is-collapsed');
  }));

  qsa('[data-ide-tab]').forEach(tab => tab.addEventListener('click', () => {
    qsa('[data-ide-tab]').forEach(node => node.classList.toggle('active', node === tab));
    qsa('[data-ide-content]').forEach(node => node.hidden = node.dataset.ideContent !== tab.dataset.ideTab);
  }));

  const resize = qs('#ideResize');
  const workspace = qs('.ide-workspace');
  resize?.addEventListener('mousedown', event => {
    event.preventDefault();
    const startY = event.clientY;
    const startHeight = qs('#bottomPanel')?.getBoundingClientRect().height || 190;
    const move = moveEvent => {
      const next = Math.max(120, Math.min(420, startHeight + startY - moveEvent.clientY));
      if (workspace) workspace.style.gridTemplateRows = `minmax(360px, 1fr) ${next}px`;
    };
    const stop = () => { document.removeEventListener('mousemove', move); document.removeEventListener('mouseup', stop); };
    document.addEventListener('mousemove', move);
    document.addEventListener('mouseup', stop);
  });

  document.addEventListener('keydown', event => {
    if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') { event.preventDefault(); form?.requestSubmit(); }
  });
  form?.addEventListener('submit', event => {
    if (!pendingFiles.size) return;
    event.preventDefault();
    const data = new FormData(form);
    data.delete('files'); data.delete('code');
    pendingFiles.forEach(file => data.append('files', file, file.name));
    fetch(form.action, { method: 'POST', body: data }).then(response => window.location.href = response.url || form.action);
  });

  renderFiles(); refresh();

  const initMonaco = () => {
    const loader = window.require;
    if (!loader || !qs('#monacoEditor')) return;
    loader.config({ paths: { vs: 'https://cdn.jsdelivr.net/npm/monaco-editor@0.52.2/min/vs' } });
    loader(['vs/editor/editor.main'], api => {
      monacoApi = api;
      monacoEditor = api.editor.create(qs('#monacoEditor'), {
        value: fallback?.value || '',
        language: monacoLanguage(),
        theme: document.documentElement.dataset.theme === 'light' ? 'vs' : 'vs-dark',
        automaticLayout: true, minimap: { enabled: true }, lineNumbers: 'on',
        fontSize: 13, fontFamily: 'JetBrains Mono, monospace', scrollBeyondLastLine: false,
        renderLineHighlight: 'all', smoothScrolling: true, tabSize: 4,
      });
      if (fallback) fallback.style.display = 'none';
      monacoEditor.onDidChangeModelContent(() => { if (fallback) fallback.value = monacoEditor.getValue(); debouncedRefresh(); });
      const mode = qs('#editorMode');
      if (mode) mode.innerHTML = 'Monaco editor · <kbd>Ctrl</kbd>+<kbd>Enter</kbd> to analyze';
      refresh();
    }, () => { toast('Monaco unavailable; using the built-in editor.', 'error'); });
  };
  setTimeout(initMonaco, 60);
});
